#!/usr/bin/env python3
"""Generate the shipped board catalog (requires PyYAML, no ROS dependency).

Run from the repository root:
  python3 depthai_descriptions/scripts/generate_board_models.py

Board geometry is generated separately from hand-maintained visual configuration and deprecated legacy poses.
Meshes are used only when an exact model mesh exists. No geometry is invented
for disconnected or malformed board graphs.
"""

import argparse
import json
from pathlib import Path

import yaml

from board_to_urdf import convert


DESCRIPTIONS = Path(__file__).resolve().parents[1]
ALIASES = {'OAK4-D': 'OAK-4-D', 'OAK4-S': 'OAK-4-S'}


def generate(boards, meshes):
    models, unsupported = {}, {}
    for path in sorted(boards.glob('*.json')):
        model = path.stem
        try:
            board = json.loads(path.read_text())
            config = board.get('board_config', board)
            # Board mode always uses the unique terminal sensor as its origin.
            reference = None
            native = convert(board, reference, 'native')
            optical = convert(board, reference, 'optical')
        except (ValueError, KeyError, TypeError) as exc:
            unsupported[model] = str(exc)
            continue

        offset = [0, 0, 0]

        def xyz(pose):
            return ' '.join(format(float(v) + d, '.12g')
                            for v, d in zip(pose['xyz'].split(), offset))

        record = {'board_file': path.name, 'reference_camera': native['reference_camera'],
                  'base_offset': offset, 'mesh': model if (meshes / (model + '.stl')).exists() else None,
                  'rgb_xyz': None, 'left_xyz': None, 'right_xyz': None,
                  'extra_cameras': {}, 'imu_variants': {}}
        stereo = config.get('stereo_config', {})
        for socket, pose in native['cameras'].items():
            if socket == stereo.get('left_cam'):
                role = 'left'
            elif socket == stereo.get('right_cam'):
                role = 'right'
            elif socket == 'CAM_A':
                role = 'rgb'
            elif model == 'OAK-T' and socket == 'CAM_E':
                role = 'right'
                record['right_name'] = 'thermal'
            else:
                role = None
            camera = {'socket': socket, 'xyz': xyz(pose), 'rpy': pose['rpy']}
            if role:
                record[role + '_xyz'] = camera['xyz']
                record[role + '_rpy'] = camera['rpy']
                record[role + '_socket'] = socket
            else:
                record['extra_cameras'][socket.lower()] = camera
        for sensor, pose in native['imus'].items():
            record['imu_variants'][sensor] = {
                'name': pose['name'], 'xyz': xyz(pose),
                'native_rpy': pose['rpy'], 'optical_rpy': optical['imus'][sensor]['rpy']}
        models[model] = record
    for alias, model in ALIASES.items():
        if model in models:
            models[alias] = dict(models[model], mesh=alias if (meshes / (alias + '.stl')).exists() else None)
    return {'models': models, 'unsupported': unsupported}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--boards', type=Path,
                        default=DESCRIPTIONS.parent / 'depthai-core/shared/depthai_boards/boards')
    parser.add_argument('--output', type=Path,
                        default=DESCRIPTIONS / 'urdf/include/board_models.yaml')
    args = parser.parse_args()
    if not args.boards.is_dir():
        parser.error(f'Board directory does not exist: {args.boards}')
    catalog = generate(args.boards, DESCRIPTIONS / 'urdf/models')
    args.output.write_text('# Generated by scripts/generate_board_models.py; visual configuration is in model_config.yaml.\n'
                           + yaml.safe_dump(catalog, sort_keys=False, width=120))
    print(f"Generated {len(catalog['models'])} models; {len(catalog['unsupported'])} unresolved boards")


if __name__ == '__main__':
    main()
